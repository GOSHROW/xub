#!/usr/bin/env python3
"""Correctness experiments for midpoint multiplication; not a benchmark.

Python's native multiplication is used only as the correctness oracle.
Candidate square algorithms use shifts, additions, subtractions, and lookup.
Run: python3 .scratchpad/verify_midpoint.py --output .scratchpad/verification-results.json
"""

from __future__ import annotations

import argparse
import json
import platform
import random
from pathlib import Path
from typing import Callable


def make_square_table(bits: int = 8) -> tuple[int, ...]:
    """S[n+1] = S[n] + 2n + 1, with no multiplication."""
    result = []
    square, odd = 0, 1
    for _ in range(1 << bits):
        result.append(square)
        square += odd
        odd += 2
    return tuple(result)


SQUARE_TABLE = make_square_table()


def square_bits(value: int) -> int:
    """Read bits from the left using S(2u+e) = 4S(u)+e(4u+1)."""
    assert value >= 0
    prefix = square = 0
    for shift in range(value.bit_length() - 1, -1, -1):
        bit = (value >> shift) & 1
        square <<= 2
        if bit:
            square += (prefix << 2) + 1
        prefix = (prefix << 1) | bit
    return square


def square_set_bits(value: int) -> int:
    """Group symmetric cross terms into one shifted tail per set bit.

    If remaining = 2**i + higher, its square contributes 2**(2*i)
    and higher << (i+1), leaving higher's square for subsequent steps.
    Candidate arithmetic uses no multiplication and no negative operands.
    """
    assert value >= 0
    remaining, square = value, 0
    while remaining:
        higher = remaining & (remaining - 1)
        bit = remaining ^ higher
        position = bit.bit_length() - 1
        # The diagonal and shifted tail occupy disjoint bit positions.
        # OR forms the row; addition propagates carries between rows.
        square += (bit << position) | (higher << (position + 1))
        remaining = higher
    return square


def square_recursive(value: int) -> int:
    """Three half-width squares, with an eight-bit table as the base case."""
    assert value >= 0
    if value < len(SQUARE_TABLE):
        return SQUARE_TABLE[value]
    shift = value.bit_length() >> 1
    high = value >> shift
    low = value & ((1 << shift) - 1)
    high_square = square_recursive(high)
    low_square = square_recursive(low)
    difference_square = square_recursive(abs(high - low))
    cross = high_square + low_square - difference_square
    return (high_square << (shift << 1)) + (cross << shift) + low_square


def midpoint_product(x: int, y: int, square: Callable[[int], int]) -> int:
    """Exact unsigned midpoint formula; no fractional representation."""
    assert x >= 0 and y >= 0
    a, b = (x, y) if x <= y else (y, x)
    difference = b - a
    d = difference >> 1
    h = a + d
    product = square(h) - square(d)
    return product + a if difference & 1 else product


def make_quarter_square_table(limit: int) -> tuple[int, ...]:
    """Q[t] = floor(t^2/4), generated by Q[t+1]-Q[t]=floor((t+1)/2)."""
    result = [0]
    for t in range(limit):
        result.append(result[-1] + ((t + 1) >> 1))
    return tuple(result)


def verify() -> dict:
    checks: dict[str, int] = {}
    count = 0
    for value in range(1 << 16):
        expected = value * value
        assert square_bits(value) == expected, ("square_bits", value)
        assert square_set_bits(value) == expected, ("square_set_bits", value)
        assert square_recursive(value) == expected, ("square_recursive", value)
        count += 1
    checks["square_bits_all_unsigned_16bit_values"] = count
    checks["square_set_bits_all_unsigned_16bit_values"] = count
    checks["square_recursive_all_unsigned_16bit_values"] = count

    # Exhaustive multiplication reuses independently computed square values.
    # Large and boundary cases below call the actual square routines directly.
    bit_squares = tuple(square_bits(i) for i in range(1 << 8))
    set_bit_squares = tuple(square_set_bits(i) for i in range(1 << 8))
    recursive_squares = tuple(square_recursive(i) for i in range(1 << 8))
    quarter = make_quarter_square_table(510)
    for index, value in enumerate(quarter):
        assert value == (index * index) // 4
    checks["quarter_square_table_entries"] = len(quarter)

    count = 0
    for x in range(1 << 8):
        for y in range(1 << 8):
            expected = x * y
            assert midpoint_product(x, y, bit_squares.__getitem__) == expected
            assert midpoint_product(x, y, set_bit_squares.__getitem__) == expected
            assert midpoint_product(x, y, recursive_squares.__getitem__) == expected
            assert quarter[x + y] - quarter[abs(x - y)] == expected
            a, b = min(x, y), max(x, y)
            h = a + ((b - a) >> 1)
            bitwise_mean = (x & y) + ((x ^ y) >> 1)
            assert 0 <= h <= 255 and h == bitwise_mean == (x + y) // 2
            count += 1
    checks["midpoint_bit_square_outputs_all_ordered_8bit_pairs"] = count
    checks["midpoint_set_bit_square_outputs_all_ordered_8bit_pairs"] = count
    checks["midpoint_recursive_square_outputs_all_ordered_8bit_pairs"] = count
    checks["quarter_square_all_ordered_8bit_pairs"] = count
    checks["overflow_free_average_all_ordered_8bit_pairs"] = count

    rng = random.Random(0x584255)
    widths = (1, 2, 7, 8, 9, 15, 16, 17, 31, 32, 33, 63, 64, 65,
              127, 128, 129, 255, 256, 257, 511, 512, 513, 1024, 2048, 4096)
    square_cases: set[int] = {0, 1, 2, 3}
    product_cases: set[tuple[int, int]] = {(0, 0), (1, 0), (0, 1), (1, 1)}
    for width in widths:
        power = 1 << width
        maximum = power - 1
        square_cases.update((power - 2, maximum, power, power + 1))
        sparse = (1 << (width - 1)) | (1 << (width >> 1)) | 1
        alternating = sum(1 << i for i in range(0, width, 2))
        square_cases.update((sparse, alternating))
        for _ in range(8):
            x = rng.getrandbits(width)
            y = rng.getrandbits(width)
            square_cases.add(x)
            product_cases.add((x, y))
            product_cases.add((y, x))
        boundaries = (
            (0, maximum), (1, maximum), (2, maximum),
            (maximum, maximum), (maximum, maximum - 1),
            (maximum, maximum - 2), (power, power + 1),
            (power, power + 2), (maximum, 1 << (width >> 1)),
            (power, 1), (sparse, sparse + 2), (alternating, sparse),
        )
        for x, y in boundaries:
            if x < 0 or y < 0:
                continue
            product_cases.add((x, y))
            product_cases.add((y, x))

    for value in sorted(square_cases):
        expected = value * value
        assert square_bits(value) == expected
        assert square_set_bits(value) == expected
        assert square_recursive(value) == expected
    checks["square_bits_deterministic_large_and_boundary_values"] = len(square_cases)
    checks["square_set_bits_deterministic_large_and_boundary_values"] = len(square_cases)
    checks["square_recursive_deterministic_large_and_boundary_values"] = len(square_cases)

    parity_classes: set[tuple[int, int]] = set()
    for x, y in sorted(product_cases):
        expected = x * y
        assert midpoint_product(x, y, square_bits) == expected, ("midpoint_bits", x, y)
        assert midpoint_product(x, y, square_set_bits) == expected, ("midpoint_set_bits", x, y)
        assert midpoint_product(x, y, square_recursive) == expected, ("midpoint_recursive", x, y)
        a, b = min(x, y), max(x, y)
        d = (b - a) >> 1
        h = a + d
        width = max(1, x.bit_length(), y.bit_length())
        assert 0 <= h < (1 << width)
        assert h == (x & y) + ((x ^ y) >> 1) == (x + y) // 2
        assert h - d == a
        parity_classes.add((x & 1, y & 1))
    assert len(parity_classes) == 4
    checks["midpoint_bit_algorithm_large_and_boundary_pairs"] = len(product_cases)
    checks["midpoint_set_bit_algorithm_large_and_boundary_pairs"] = len(product_cases)
    checks["midpoint_recursive_algorithm_large_and_boundary_pairs"] = len(product_cases)
    checks["overflow_free_average_large_and_boundary_pairs"] = len(product_cases)

    return {
        "status": "passed",
        "purpose": "Correctness only; these checks make no performance claim.",
        "python": platform.python_version(),
        "machine": platform.machine(),
        "seed": "0x584255",
        "checks": checks,
        "maximum_tested_square_input_bits": max(v.bit_length() for v in square_cases),
        "maximum_tested_product_operand_bits": max(max(x.bit_length(), y.bit_length()) for x, y in product_cases),
        "maximum_random_width_bits": max(widths),
        "coverage": [
            "All ordered unsigned eight-bit input pairs",
            "All unsigned sixteen-bit values for all three square routines",
            "Zero, equal inputs, reversed inputs, all four parity classes",
            "Powers of two, neighboring values, maximum fixed-width values",
            "Nearby and highly unequal inputs, deterministic random inputs",
            "Sparse, alternating, and dense bits; sparse inputs with dense half-differences",
            "Integer average remains within the original operand width",
        ],
        "notes": [
            "The exhaustive product sweep caches each square routine's outputs.",
            "Large and boundary product cases invoke each square routine directly.",
            "Boundary values just above 2^4096 have 4097 bits.",
            "A successful finite check supports, but does not replace, the algebraic proof.",
        ],
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    report = json.dumps(verify(), indent=2) + "\n"
    if args.output:
        args.output.write_text(report, encoding="utf-8")
    print(report, end="")
